/** 合并通用方向 + 学校特色方向，返回结构化列表 */
function mkDirections(school, program) {
  const code = program.majorCode;
  const sc = school.c || school.code; // 兼容原始数据对象(s.c)与 allSchools 对象(s.code)
  const base = (RESEARCH_DETAIL[code] && RESEARCH_DETAIL[code].dirs) || [];
  const extra = (SCHOOL_RESEARCH[sc] && SCHOOL_RESEARCH[sc][code]) || [];

  const out = base.map((d) => Object.assign({ schoolSpecific: false }, d));
  const seen = {};
  base.forEach((d) => { seen[d.name] = true; });
  extra.forEach((name) => {
    if (seen[name]) return; // 已存在则不重复
    seen[name] = true;
    out.push({ name, desc: '该校该方向的代表性平台/团队方向，具体导师与课题以当年招生目录为准。', jobs: '结合该校优势行业就业。', schoolSpecific: true });
  });

  if (!out.length) {
    out.push({ name: '计算机科学与技术（具体方向以院校招生目录为准）', desc: '该专业方向以院校当年招生专业目录为准。', jobs: '计算机类通用就业。', schoolSpecific: false });
  }
  return out;
}

