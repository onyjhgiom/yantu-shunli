/* ---------------- 读取 ---------------- */
function all() { return ITEMS.slice(); }
function categories() { return CATEGORIES.slice(); }
function get(id) { return ITEMS.find((x) => x.id === id) || null; }

function byCat(cat) {
  if (!cat || cat === 'all') return all();
  return ITEMS.filter((x) => x.cat === cat);
}

/** 中文分词检索（2 字滑窗 + 停用词 + 长术语保留） */
const STOP = ['的', '了', '是', '在', '和', '与', '及', '或', '如何', '怎么', '为什么', '我们', '他们', '可以', '一个', '这个', '那个', '以及', '对于'];
function tokenize(s) {
  s = (s || '').toLowerCase();
  const tokens = [];
  for (let i = 0; i < s.length - 1; i++) tokens.push(s.substr(i, 2));
  return tokens.filter((t) => !STOP.includes(t));
}
function search(keyword) {
  const kw = (keyword || '').trim();
  if (!kw) return all();
  const qt = tokenize(kw);
  const scored = ITEMS.map((it) => {
    const blob = (it.title + ' ' + it.sub + ' ' + (it.tags || []).join(' ') + ' ' + it.body.join(' ')).toLowerCase();
    let score = 0;
    if (it.title.toLowerCase().indexOf(kw.toLowerCase()) >= 0) score += 20;
    if (it.sub.toLowerCase().indexOf(kw.toLowerCase()) >= 0) score += 8;
    (it.tags || []).forEach((t) => { if (t.toLowerCase().indexOf(kw.toLowerCase()) >= 0) score += 6; });
    qt.forEach((t) => { if (blob.indexOf(t) >= 0) score += 1; });
    return { it, score };
  }).filter((x) => x.score > 0);
  scored.sort((a, b) => b.score - a.score);
  return scored.map((x) => x.it);
}

/* ---------------- 收藏 ---------------- */
function favs() { return db.get(db.KEYS.newsFavs, []); }
function isFav(id) { return favs().indexOf(id) >= 0; }
function toggleFav(id) {
  const f = favs();
  const i = f.indexOf(id);
  if (i >= 0) f.splice(i, 1); else f.unshift(id);
  db.set(db.KEYS.newsFavs, f);
  return f;
}

/* ---------------- 已读 ---------------- */
function readIds() { return db.get(db.KEYS.news, []); }
function isRead(id) { return readIds().indexOf(id) >= 0; }
function markRead(id) {
  const r = readIds();
  if (r.indexOf(id) < 0) { r.unshift(id); db.set(db.KEYS.news, r); }
}

module.exports = {
  all, categories, get, byCat, search,
  favs, isFav, toggleFav, readIds, isRead, markRead
};
