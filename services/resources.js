function toggleFav(id) {
  const list = favs();
  const i = list.indexOf(id);
  if (i >= 0) list.splice(i, 1); else list.unshift(id);
  db.set(db.KEYS.resFavs, list);
  return list.indexOf(id) >= 0;
}

function favList() {
  return favs().map(detail).filter(Boolean).map((i) => toCard(i));
}

/** 生成可存入笔记的纯文本 */
function toNoteText(id) {
  const d = detail(id);
  if (!d) return '';
  const lines = [`【${d.catName}】${d.title}`, `适用：${d.scopeText}`];
  if (d.sub) lines.push(d.sub);
  lines.push('');
  (d.body || []).forEach((b) => lines.push(b));
  return lines.join('\n');
}

