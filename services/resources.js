function appliesTo(item, code) {
  if (!code) return true;
  return !item.applies || item.applies.indexOf(code) >= 0;
}

function countOf(key, code) {
  let list = ITEMS.filter((i) => appliesTo(i, code));
  if (!key || key === 'all') return list.length;
  return list.filter((i) => i.cat === key).length;
}

/** 分类浏览；code 为空表示不过滤 */
function byCategory(cat, keyword, code) {
  let list = ITEMS.filter((i) => appliesTo(i, code));
  if (cat && cat !== 'all') list = list.filter((i) => i.cat === cat);
  const kw = (keyword || '').trim().toLowerCase();
  if (kw) list = list.filter((i) => matchItem(i, kw));
  return list.map((i) => toCard(i));
}

function matchItem(item, kw) {
  return scoreOf(item, kw) > 0;
}

/**
 * 单条匹配打分（0 = 不匹配）
 * 注意：hot 加权只在「已命中」时生效，否则热门条目会在完全无关的问题里被误召回。
 */
/**
 * 检索字段预计算（懒构建，每个条目只算一次）
 *
 * 原实现每次打分都要对 title / sub / tags / body 重新 toLowerCase，
 * 还要 some() 遍历 tags 和十几到几十段正文。一次 searchSmart 查询有 3-5 个 token、
 * 每个 token 扫全部 40 篇，等于把同一批字符串反复转成小写几百次。
 * 这里把四个字段的小写串缓存下来，打分退化成 4 次字符串 indexOf。
 *
 * 权重保持原样：标题 20 > 摘要 8 > 标签 6 > 正文 1。
 */
const _FIELD_CACHE = Object.create(null);

function fieldsOf(item) {
  let f = _FIELD_CACHE[item.id];
  if (f) return f;
  f = {
    title: item.title ? item.title.toLowerCase() : '',
    sub: item.sub ? item.sub.toLowerCase() : '',
    tags: (item.tags || []).join(' ').toLowerCase(),
    body: (item.body || []).join('\n').toLowerCase()
  };
  _FIELD_CACHE[item.id] = f;
  return f;
}

function scoreOf(item, kw) {
  const f = fieldsOf(item);
  let score = 0;
  // 标题命中 >> 摘要 > 标签 > 正文。正文权重压到 1，避免长条目「什么都沾一点」而霸榜
  if (f.title.indexOf(kw) >= 0) score += 20;
  if (f.sub.indexOf(kw) >= 0) score += 8;
  if (f.tags.indexOf(kw) >= 0) score += 6;
  if (f.body.indexOf(kw) >= 0) score += 1;
  if (score > 0 && item.hot) score += 2;
  return score;
}

/* ---------- 检索结果缓存 ---------- */

const _ITEM_MAP = Object.create(null);
let _ITEM_MAP_BUILT = false;
function itemById(id) {
  if (!_ITEM_MAP_BUILT) {
    ITEMS.forEach((i) => { _ITEM_MAP[i.id] = i; });
    _ITEM_MAP_BUILT = true;
  }
  return _ITEM_MAP[id];
}

/**
 * 单个 token 在全部条目上的命中表，按 token+报考方向缓存。
 * 同一个词在连续输入、多轮 AI 检索里会被问到多次，命中后直接复用。
 */
const _HIT_CACHE = Object.create(null);

function hitsOf(token, code) {
  const ck = token + '\u0001' + (code || '');
  if (Object.prototype.hasOwnProperty.call(_HIT_CACHE, ck)) return _HIT_CACHE[ck];
  const out = [];
  ITEMS.forEach((i) => {
    if (!appliesTo(i, code)) return;
    const s = scoreOf(i, token);
    if (s > 0) out.push({ id: i.id, score: s });
  });
  _HIT_CACHE[ck] = out;
  return out;
}

/** 对比型提问：区别 / 差异 / 对比 / vs / 不同 / 边界 */
const COMPARE_WORDS = ['区别', '差异', '对比', '不同', '边界', '考纲', 'vs', '哪个更', '选哪个'];
const COMPARE_TARGET = ['vs', '区别', '差异', '对比', '边界', '考纲', '不同'];

function isCompareQuery(kw) {
  return COMPARE_WORDS.some((w) => kw.indexOf(w) >= 0);
}

/** 中文/英文混合分词，用于长句检索 */
const STOP_WORDS = [
  // 疑问 / 助词
  '怎么', '怎样', '如何', '什么', '为什么', '请问', '一下', '帮我', '给我', '我想', '可以', '有没有', '有哪些',
  '区别', '差异', '总结', '介绍', '这个', '那个', '的', '了', '吗', '呢', '啊', '是', '在', '我', '你', '要',
  '做', '说', '学', '看', '问', '讲', '个',
  // 通用泛词（命中它们没有区分度，必须从检索词里剔除）
  '时候', '情况', '方面', '内容', '部分', '一般', '大概', '多少', '几个', '需要', '应该', '这样', '那样',
  '一些', '各种', '有关', '关于', '知道', '告诉', '一下', '还有', '就是', '哪些', '哪里', '怎么'
];

function tokenize(kw) {
  const s = String(kw || '').toLowerCase();
  // 允许 B+树 / 802.11 / C++ 这类带符号的术语，避免被拆碎
  const en = (s.match(/[a-z0-9][a-z0-9+_.#]{1,}/g) || []);
  let zh = s.replace(/[a-z0-9+_.#]/g, ' ');
  STOP_WORDS.forEach((w) => { zh = zh.split(w).join(' '); });
  const segs = [];
  (zh.match(/[\u4e00-\u9fa5]+/g) || []).forEach((seg) => {
    if (seg.length < 2) return;
    segs.push(seg);                       // 整段先保留（能命中复合词）
    if (seg.length <= 3) return;
    // 4 字以上再补 2 字滑窗，保证「英语作文模板」「数一和数二」这类短语能拆出有效词
    for (let i = 0; i + 2 <= seg.length; i += 1) segs.push(seg.substr(i, 2));
  });
  return en.concat(segs).filter((t, i, arr) => arr.indexOf(t) === i);
}

/**
 * 智能检索：先整句精确匹配；无结果时按分词累积打分。
 * 解决「Cache 地址怎么划分」这类长问句召回不到的问题。
 */
function searchSmart(keyword, code) {
  const kw = (keyword || '').trim().toLowerCase();
  if (!kw) return [];
  const exact = search(kw, code);
  if (exact.length) return exact;

  const tokens = tokenize(kw);
  if (!tokens.length) return [];
  const compare = isCompareQuery(kw);
  const acc = {};
  tokens.forEach((t) => {
    hitsOf(t, code).forEach((h) => {
      const i = itemById(h.id);
      if (!i) return;
      if (!acc[h.id]) acc[h.id] = { item: i, score: 0, hitTokens: [] };
      acc[h.id].score += h.score;
      acc[h.id].hitTokens.push(t);
      // 对比型提问优先返回「对比/边界/考纲」类内容
      if (compare && COMPARE_TARGET.some((w) => i.title.indexOf(w) >= 0)) acc[h.id].score += 25;
    });
  });
  const list = Object.keys(acc).map((k) => acc[k]);
  // 分数优先（标题权重已远高于正文），同分再比命中词数
  list.sort((a, b) => (b.score - a.score) || (b.hitTokens.length - a.hitTokens.length));
  return list.map((x) => Object.assign(toCard(x.item), {
    hits: (x.item.body || []).filter((b) => b.toLowerCase().indexOf(x.hitTokens[0]) >= 0).slice(0, 2)
  }));
}

function toCard(item) {
  const cat = CATEGORIES.find((c) => c.key === item.cat) || {};
  return {
    id: item.id,
    cat: item.cat,
    catName: cat.name || '其他',
    catIcon: cat.icon || '·',
    title: item.title,
    sub: item.sub,
    tags: item.tags || [],
    hot: !!item.hot,
    fav: isFav(item.id),
    applies: item.applies || ['11408', '22408'],
    scopeText: scopeText(item),
    lines: (item.body || []).length,
    preview: (item.body || []).find((b) => b.trim()) || ''
  };
}

/** 适用范围文案 */
function scopeText(item) {
  const a = item.applies || ['11408', '22408'];
  if (a.length >= 2) return '通用';
  return a[0] === '11408' ? '仅数一/英一(学硕)' : '仅数二/英二(专硕)';
}

/** 全文搜索（跨分类） */
function search(keyword, code) {
  const kw = (keyword || '').trim().toLowerCase();
  if (!kw) return [];
  const scored = ITEMS.filter((i) => appliesTo(i, code))
    .map((i) => ({ item: i, score: scoreOf(i, kw) }))
    .filter((x) => x.score > 0);
  scored.sort((a, b) => b.score - a.score);
  return scored.map((x) => Object.assign(toCard(x.item), {
    hits: (x.item.body || []).filter((b) => b.toLowerCase().indexOf(kw) >= 0).slice(0, 2)
  }));
}

function detail(id) {
  const item = ITEMS.find((i) => i.id === id);
  if (!item) return null;
  const cat = CATEGORIES.find((c) => c.key === item.cat) || {};
  return Object.assign({}, item, {
    catName: cat.name || '其他',
    scopeText: scopeText(item),
    fav: isFav(id)
  });
}

function hot(limit, code) {
  const list = ITEMS.filter((i) => i.hot && appliesTo(i, code));
  return list.slice(0, limit || 6).map((i) => toCard(i));
}

/** 按科目推荐（供 AI 与首页智能推荐调用） */
function recommendFor(subjectKey, code, limit) {
  const map = {
    math: ['math'],
    english: ['english'],
    politics: ['politics'],
    major: ['cs408'],
    other: ['method', 'plan']
  };
  const cats = map[subjectKey] || ['method'];
  const list = ITEMS.filter((i) => cats.indexOf(i.cat) >= 0 && appliesTo(i, code));
  list.sort((a, b) => (b.hot ? 1 : 0) - (a.hot ? 1 : 0));
  return list.slice(0, limit || 3).map((i) => toCard(i));
}

/** 按阶段推荐 */
function recommendByPhase(phase, code, limit) {
  const map = {
    prepare: ['cs408', 'method', 'math', 'plan'],
    sprint: ['politics', 'english', 'math', 'cs408'],
    retest: ['retest', 'adjust'],
    unset: ['plan', 'method', 'cs408']
  };
  const cats = map[phase] || ['method'];
  const list = ITEMS.filter((i) => cats.indexOf(i.cat) >= 0 && appliesTo(i, code));
  list.sort((a, b) => (b.hot ? 1 : 0) - (a.hot ? 1 : 0));
  return list.slice(0, limit || 3).map((i) => toCard(i));
}

/** 与用户薄弱科目联动的推荐（AI 用） */
